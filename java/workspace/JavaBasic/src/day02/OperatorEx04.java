package day02;

public class OperatorEx04 {
	public static void main(String[] args) {

		int a = 6;
		int b = 5;

		a += 3; // a = a + 3;
		b = +3; // b = 3; //주의하셈
		System.out.println(a);
		System.out.println(b);

		a -= 4;  // 9-4 = 5
		a *= 10; // 5 * 10 = 50
		a /= 3;  // 50 / 3 = 16
		a %= 2;  // 16 % 2 = 0

	}
}
